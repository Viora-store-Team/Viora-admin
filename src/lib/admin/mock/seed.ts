/** تاريخ مرجعي ثابت — كل التواريخ مشتقة منه بدل Date.now() */
const BASE = new Date("2026-08-21T12:00:00Z");

export function daysAgo(n: number): string {
  const d = new Date(BASE);
  d.setUTCDate(d.getUTCDate() - n);
  return d.toISOString().slice(0, 10);
}

export function hoursAgo(n: number): string {
  const d = new Date(BASE);
  d.setUTCHours(d.getUTCHours() - n);
  return d.toISOString();
}

/** توزيع حتمي بسيط — بيعطي تنوّع بلا عشوائية */
export function spread(index: number, max: number, offset = 0): number {
  return ((index * 7 + offset * 13) % max) + 1;
}

