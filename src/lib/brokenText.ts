/**
 * كشف النصوص اللي ترميزها انكسر **قبل ما تنحفظ** بقاعدة البيانات.
 *
 * ⚠️ هاد كشف مش إصلاح — والفرق مهم.
 *
 * في نوعين من كسر الترميز. النوع القابل للإصلاح هو الـmojibake الكلاسيكي
 * (بايتات UTF-8 انقرت كـWindows-1256 مثلاً): الحروف الأصلية لسا موجودة
 * بشكل مشوّه، فبتقدر تعكس العملية وترجّع النص. أما اللي عنا فهو النوع
 * **التاني**: البايتات انبدلت فعلياً — إما بـ `U+FFFD` (المحرف البديل) أو
 * بعلامات استفهام ASCII — وقت الكتابة. المعلومة انمسحت من الوجود، وما في
 * أي دالة بتقدر ترجّعها.
 *
 * فحصنا الصفوف: متجر 28 اسمه `"???? ????? 2275120742"` ومتجر 180 اسمه
 * `"���� …"`. الاتنين ما إلهم استرجاع.
 *
 * فاللي منعمله هون: نكشفهم ونعرض بديل واضح («متجر #180») بدل ما نرمي
 * رموز مكسّرة بوجه المشرف. **الإصلاح الحقيقي بقاعدة البيانات** — تصحيح
 * الصف أو حذفه، مش شغل واجهة.
 */

/** المحرف البديل U+FFFD — بينحط محل بايت ما انقرأش كـUTF-8 */
const REPLACEMENT = "�";

/** أي حرف بأي لغة — الأرقام والرموز مش حروف */
const HAS_LETTER = /\p{L}/u;

/**
 * النص مكسور بلا رجعة؟
 *
 * شرطين، والتاني متحفّظ عمداً:
 *
 * ١. فيه `U+FFFD` — ما في نص شرعي بيحتوي المحرف البديل.
 * ٢. فيه شلّة `???` **و** ما فيه ولا حرف واحد. الشرط التاني بيحمي أسماء
 *    شرعية زي `"محل ؟؟؟"` (علامة الاستفهام العربية محرف تاني أصلاً) أو
 *    `"Test ??? shop"` — وجود أي حرف معناه إن النص لسا مقروء.
 *
 * `"{{zft store}}"` **مش** مكسور — هاد متغيّر بوستمان ما انحلّ، وبينعرض
 * متل ما هو عشان يبان إنه بيانات تجريبية مش عطل ترميز.
 */
export function isBrokenText(value: string | null | undefined): boolean {
  if (!value) return false;
  if (value.includes(REPLACEMENT)) return true;
  return /\?{3,}/.test(value) && !HAS_LETTER.test(value);
}

/**
 * القيمة للعرض، أو `null` لو كانت مكسورة.
 *
 * بترجّع `null` مش شرطة، عشان `InfoGrid` هو اللي يقرّر شكل الفراغ —
 * نفس معاملة أي حقل ناقص من السيرفر.
 */
export function textOrNull(value: string | null | undefined): string | null {
  if (!value || isBrokenText(value)) return null;
  return value;
}
